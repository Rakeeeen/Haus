"""Writes src/ui/illustrations.tsx from shapes.py. Run: python3 scripts/illustrations/build.py"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from shapes import ILLUSTRATIONS

out = os.path.join(HERE, '..', '..', 'src', 'ui', 'illustrations.tsx')
data = {}
for name, draw in ILLUSTRATIONS.items():
    pen = draw()
    layers = getattr(pen, 'done', []) + [(pen.paper, pen.ink)]
    data[name] = [[paper, ink] for paper, ink in layers]

def comp(name):
    return name[0].upper() + name[1:] + 'Illustration'

ts = ['// Generated by scripts/illustrations/build.py. Edit the drawings there, not here.',
      "import React from 'react';",
      '',
      "/** Each layer is [paper shapes, ink shapes], painted in order so ink can sit under paper. */",
      'type Layers = ReadonlyArray<readonly [readonly string[], readonly string[]]>;',
      '']
for name, layers in data.items():
    ts.append(f'const {name.upper()}: Layers = {json.dumps(layers, separators=(",", ":"))};')
ts += ['',
       '/** Paper is --icon-paper, ink follows the text colour, so both follow the theme. */',
       'const Drawing: React.FC<{ layers: Layers; className?: string }> = ({ layers, className }) => (',
       '  <svg viewBox="0 0 1000 1000" className={className} aria-hidden="true">',
       '    {layers.map(([paper, ink], i) => (',
       '      <React.Fragment key={i}>',
       '        <g fill="var(--icon-paper)">{paper.map((d, j) => <path key={j} d={d} />)}</g>',
       '        <g fill="currentColor">{ink.map((d, j) => <path key={j} d={d} />)}</g>',
       '      </React.Fragment>',
       '    ))}',
       '  </svg>',
       ');',
       '']
for name in data:
    ts.append(f'export const {comp(name)}: React.FC<{{ className?: string }}> = ({{ className }}) => <Drawing layers={{{name.upper()}}} className={{className}} />;')
open(out, 'w').write('\n'.join(ts) + '\n')
print('wrote', os.path.relpath(out), os.path.getsize(out) // 1024, 'KB')
